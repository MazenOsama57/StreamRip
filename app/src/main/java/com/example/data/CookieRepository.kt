package com.example.data

import android.content.Context
import android.webkit.CookieManager
import java.io.File

class CookieRepository(private val context: Context) {

    val cookiesFile: File
        get() = File(context.filesDir, "cookies.txt")

    fun hasCookies(): Boolean {
        return cookiesFile.exists() && cookiesFile.length() > 20
    }

    fun getCookiesFilePath(): String? {
        return if (hasCookies()) cookiesFile.absolutePath else null
    }

    fun saveRawCookiesTxt(content: String): Boolean {
        return try {
            cookiesFile.writeText(content.trim())
            true
        } catch (e: Exception) {
            false
        }
    }

    fun saveFromCookieManager(url: String = "https://www.youtube.com"): Boolean {
        return try {
            val cookieStr = CookieManager.getInstance().getCookie(url)
            if (cookieStr.isNullOrBlank()) return false
            convertAndSaveCookies(cookieStr)
        } catch (e: Exception) {
            false
        }
    }

    fun convertAndSaveCookies(cookieHeader: String): Boolean {
        return try {
            val sb = StringBuilder()
            sb.append("# Netscape HTTP Cookie File\n")
            sb.append("# Generated by StreamRip for yt-dlp authentication\n\n")

            val pairs = cookieHeader.split(";")
            for (p in pairs) {
                val trimmed = p.trim()
                val eqIdx = trimmed.indexOf('=')
                if (eqIdx > 0) {
                    val key = trimmed.substring(0, eqIdx).trim()
                    val value = trimmed.substring(eqIdx + 1).trim()
                    // domain, flag, path, secure, expiration, name, value
                    sb.append(".youtube.com\tTRUE\t/\tTRUE\t2147483647\t$key\t$value\n")
                    sb.append(".google.com\tTRUE\t/\tTRUE\t2147483647\t$key\t$value\n")
                }
            }

            cookiesFile.writeText(sb.toString())
            true
        } catch (e: Exception) {
            false
        }
    }

    fun clearCookies() {
        try {
            if (cookiesFile.exists()) {
                cookiesFile.delete()
            }
            CookieManager.getInstance().removeAllCookies(null)
            CookieManager.getInstance().flush()
        } catch (_: Exception) {}
    }
}
